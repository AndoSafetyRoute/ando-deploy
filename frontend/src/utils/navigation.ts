// 공용 "홈으로" 네비게이션 헬퍼.
//
// 문제: 앱 전역의 "홈" 아이콘/버튼들이 전부 router.replace("/") 를 썼다. replace 는
// 스택 맨 위(지금 화면) 하나만 "/"로 바꿔치기할 뿐, 그 아래 쌓인 화면들(검색→경로→
// 비교→안내→평가→상세 처럼 깊어질 수 있는 흐름)은 그대로 남는다. 그래서 "홈"을 눌러
// 화면은 홈으로 보여도, 그 다음 뒤로가기를 누르면 그 남아있던 옛 스택을 끝없이
// 거슬러 올라간다.
//
// 해결: dismissTo("/") 로 "/" 위에 쌓인 화면을 전부 걷어내고 그 자리에서 새로
// 시작한다 — 이후 뒤로가기는 더 이상 갈 곳이 없다. "/"가 스택에 없는 예외적인
// 경우(딥링크 등)엔 dismissTo 가 실패할 수 있어 replace 로 안전하게 폴백한다.
import { router } from "expo-router";

export function goHome(): void {
  try {
    router.dismissTo("/");
  } catch {
    router.replace("/");
  }
}
